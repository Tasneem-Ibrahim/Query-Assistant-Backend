-- Apply before enabling the expanded Log Management page in cloud mode.
create table if not exists public.qa_activity_events (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  category text not null check (category in ('user-details', 'knowledge-base', 'role-management')),
  actor_id text not null,
  target text,
  action text not null
);

create index if not exists qa_activity_events_category_id on public.qa_activity_events (category, id desc);
alter table public.qa_activity_events enable row level security;
revoke all on public.qa_activity_events from public, anon, authenticated;
grant select, insert on public.qa_activity_events to service_role;
grant usage on sequence public.qa_activity_events_id_seq to service_role;
